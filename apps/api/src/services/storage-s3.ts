import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';

import type { StorageService, StoredObject } from './storage.ts';

/** A hung connection must not hold the upload route forever. */
export const S3_REQUEST_TIMEOUT_MS = 15_000;

/**
 * Minimal S3 client surface used by the adapter.
 *
 * Tests inject a fake with a `send` method, so the adapter never needs a
 * network or real credentials. The real `S3Client` satisfies this shape.
 */
export interface S3ClientLike {
  send(command: unknown, options?: { readonly abortSignal?: AbortSignal }): Promise<unknown>;
}

export interface S3StorageOptions {
  readonly endpoint: string;
  readonly region: string;
  readonly bucket: string;
  readonly accessKeyId: string;
  readonly secretAccessKey: string;
  /** Silo/MinIO require path-style addressing; R2 and AWS accept it too. */
  readonly forcePathStyle: boolean;
  /** Injected test double. Omitted in production to build the SDK client. */
  readonly client?: S3ClientLike;
}

/** Credential-safe storage failure: never echoes keys, secrets or endpoints. */
export class StorageError extends Error {
  readonly operation: 'put' | 'get' | 'delete';
  readonly key: string;

  constructor(
    operation: 'put' | 'get' | 'delete',
    key: string,
    options?: { readonly cause?: unknown },
  ) {
    super(`S3 ${operation} falló para la clave "${key}".`, options);
    this.name = 'StorageError';
    this.operation = operation;
    this.key = key;
  }
}

function isNotFound(error: unknown): boolean {
  if (typeof error !== 'object' || error === null) {
    return false;
  }

  const candidate = error as {
    readonly name?: unknown;
    readonly Code?: unknown;
    readonly $metadata?: { readonly httpStatusCode?: unknown };
  };

  return (
    candidate.name === 'NoSuchKey' ||
    candidate.Code === 'NoSuchKey' ||
    candidate.$metadata?.httpStatusCode === 404
  );
}

function isAsyncIterable(value: unknown): value is AsyncIterable<Uint8Array | string> {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof (value as { [Symbol.asyncIterator]?: unknown })[Symbol.asyncIterator] === 'function'
  );
}

/**
 * Normalises the several bodies the SDK may return: a `Buffer`/`Uint8Array`
 * from tests, the browser-style `transformToByteArray()` or a Node stream.
 */
async function readBody(body: unknown): Promise<Buffer | null> {
  if (body === undefined || body === null) {
    return null;
  }

  if (body instanceof Uint8Array) {
    return Buffer.from(body);
  }

  const withTransform = body as { readonly transformToByteArray?: () => Promise<Uint8Array> };

  if (typeof withTransform.transformToByteArray === 'function') {
    return Buffer.from(await withTransform.transformToByteArray());
  }

  if (isAsyncIterable(body)) {
    const chunks: Buffer[] = [];

    for await (const chunk of body) {
      chunks.push(typeof chunk === 'string' ? Buffer.from(chunk) : Buffer.from(chunk));
    }

    return Buffer.concat(chunks);
  }

  throw new Error('S3 devolvió un cuerpo de objeto no soportado.');
}

/**
 * Private S3-compatible adapter for Silo/MinIO, Cloudflare R2 and AWS S3.
 *
 * Keys are generated by the server; the adapter neither builds URLs nor makes
 * objects public. `get` returns `null` when the object does not exist and
 * wraps every other SDK failure in `StorageError`, preserving the original
 * error as `cause` without copying credential material into the message.
 */
export function createS3StorageService(options: S3StorageOptions): StorageService {
  const client: S3ClientLike =
    options.client ??
    new S3Client({
      endpoint: options.endpoint,
      region: options.region,
      forcePathStyle: options.forcePathStyle,
      maxAttempts: 2,
      credentials: {
        accessKeyId: options.accessKeyId,
        secretAccessKey: options.secretAccessKey,
      },
    });

  /** Fresh signal per operation: a previous abort must not affect the next one. */
  function requestOptions(): { readonly abortSignal: AbortSignal } {
    return { abortSignal: AbortSignal.timeout(S3_REQUEST_TIMEOUT_MS) };
  }

  return {
    async put(key: string, body: Buffer, contentType: string): Promise<void> {
      try {
        await client.send(
          new PutObjectCommand({
            Bucket: options.bucket,
            Key: key,
            Body: body,
            ContentType: contentType,
            ContentLength: body.byteLength,
          }),
          requestOptions(),
        );
      } catch (error) {
        throw new StorageError('put', key, { cause: error });
      }
    },

    async get(key: string): Promise<StoredObject | null> {
      let response: unknown;

      try {
        response = await client.send(
          new GetObjectCommand({
            Bucket: options.bucket,
            Key: key,
          }),
          requestOptions(),
        );
      } catch (error) {
        if (isNotFound(error)) {
          return null;
        }

        throw new StorageError('get', key, { cause: error });
      }

      try {
        const output = response as {
          readonly Body?: unknown;
          readonly ContentType?: string;
        };
        const body = await readBody(output.Body);

        if (body === null) {
          throw new Error('S3 devolvió una respuesta sin cuerpo.');
        }

        return {
          body,
          contentType: output.ContentType ?? 'application/octet-stream',
        };
      } catch (error) {
        throw new StorageError('get', key, { cause: error });
      }
    },

    async delete(key: string): Promise<void> {
      try {
        await client.send(
          new DeleteObjectCommand({
            Bucket: options.bucket,
            Key: key,
          }),
          requestOptions(),
        );
      } catch (error) {
        throw new StorageError('delete', key, { cause: error });
      }
    },
  };
}
