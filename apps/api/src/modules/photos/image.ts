import {
  can,
  errorResponseSchema,
  imageMimeTypeSchema,
  photoImageQuerySchema,
  photoParamsSchema,
  type PermissionActor,
  type PermissionCircle,
  type PhotoImageSize,
} from '@memora/shared';

import type { FastifyReply } from 'fastify';

import type { AppConfig } from '../../config.ts';
import { ApiError } from '../../errors.ts';
import type { PrismaClient } from '../../generated/prisma/client.ts';
import { SESSION_SECURITY_SCHEME } from '../../plugins/swagger.ts';
import type { StoredObject } from '../../services/index.ts';
import type { MemoraServer } from '../../types.ts';
import { requirePrisma } from '../auth/guards.ts';
import { resolveSession } from '../auth/session.ts';
import { resolveCircleRole, toCircleSettings } from '../circles/dto.ts';

const PHOTOS_TAG = 'Photos';

const sessionSecurity = [{ [SESSION_SECURITY_SCHEME]: [] }];

/** One hour, as frozen by ADR-0006 and the API contract. */
export const IMAGE_CACHE_CONTROL = 'private, max-age=3600';

/** Variants generated by the upload pipeline are always WebP. */
const VARIANT_CONTENT_TYPE = 'image/webp';

/** Fallback for a persisted `mimeType` outside the shared image enum. */
const FALLBACK_CONTENT_TYPE = 'application/octet-stream';

interface PhotoImageRecord {
  readonly id: string;
  readonly mimeType: string;
  readonly updatedAt: Date;
  readonly thumbKey: string;
  readonly displayKey: string;
  readonly originalKey: string;
  readonly circle: PermissionCircle;
  readonly role: PermissionActor['role'];
}

/**
 * Loads the photo only when the requesting user is still a member of its
 * circle. A missing photo, a photo from another circle and a circle the user
 * left all return `null`, so the route must map every case to `404`.
 *
 * The select is deliberately narrow: storage keys stay on the server and the
 * response never echoes the row.
 */
async function findPhotoForMember(
  prisma: PrismaClient,
  photoId: string,
  userId: string,
): Promise<PhotoImageRecord | null> {
  const photo = await prisma.photo.findFirst({
    where: {
      id: photoId,
      circle: { memberships: { some: { userId } } },
    },
    select: {
      id: true,
      mimeType: true,
      updatedAt: true,
      thumbKey: true,
      displayKey: true,
      originalKey: true,
      circle: {
        select: {
          id: true,
          ownerId: true,
          settings: true,
          memberships: {
            where: { userId },
            select: { role: true },
            take: 1,
          },
        },
      },
    },
  });

  if (photo === null) {
    return null;
  }

  const membership = photo.circle.memberships[0];

  // The membership filter above guarantees a row; the check is a fail-closed
  // guard against a concurrent removal between the two reads.
  if (membership === undefined) {
    return null;
  }

  return {
    id: photo.id,
    mimeType: photo.mimeType,
    updatedAt: photo.updatedAt,
    thumbKey: photo.thumbKey,
    displayKey: photo.displayKey,
    originalKey: photo.originalKey,
    circle: {
      id: photo.circle.id,
      ownerId: photo.circle.ownerId,
      settings: toCircleSettings(photo.circle.settings),
    },
    role: resolveCircleRole(photo.circle, userId, membership.role),
  };
}

/** Server-side key selection: the client only ever sends `size`. */
export function selectImageKey(
  photo: Pick<PhotoImageRecord, 'thumbKey' | 'displayKey' | 'originalKey'>,
  size: PhotoImageSize,
): string {
  switch (size) {
    case 'thumb':
      return photo.thumbKey;
    case 'display':
      return photo.displayKey;
    case 'original':
      return photo.originalKey;
  }
}

/** Stable weak validator over the facts that change the bytes: id, size and mtime. */
export function buildImageEtag(photoId: string, size: PhotoImageSize, updatedAt: Date): string {
  return `W/"${photoId}-${size}-${updatedAt.getTime()}"`;
}

/** Weak comparison: `W/` is ignored and multiple validators are accepted. */
export function matchesIfNoneMatch(header: string | undefined, etag: string): boolean {
  if (typeof header !== 'string' || header.length === 0) {
    return false;
  }

  const normalizedEtag = etag.replace(/^W\//, '');

  return header
    .split(',')
    .map((candidate) => candidate.trim())
    .some((candidate) => candidate === '*' || candidate.replace(/^W\//, '') === normalizedEtag);
}

function assertDownloadPermission(photo: PhotoImageRecord, userId: string): void {
  const actor: PermissionActor = { id: userId, role: photo.role };

  if (!can(actor, 'photo.download', photo.circle)) {
    throw new ApiError('FORBIDDEN');
  }
}

/**
 * `original` reports the persisted MIME type only when it is one the upload
 * pipeline accepts; a corrupted row falls back instead of echoing arbitrary
 * data into `Content-Type`.
 */
function resolveContentType(
  photo: Pick<PhotoImageRecord, 'mimeType'>,
  size: PhotoImageSize,
): string {
  if (size !== 'original') {
    return VARIANT_CONTENT_TYPE;
  }

  const mimeType = imageMimeTypeSchema.safeParse(photo.mimeType);

  return mimeType.success ? mimeType.data : FALLBACK_CONTENT_TYPE;
}

/**
 * `GET /api/photos/:photoId/image?size=thumb|display|original` (F27, ADR-0006).
 *
 * Authenticated binary delivery; the object key is chosen on the server from
 * `size`. `thumb` and `display` are available to every member of the photo's
 * circle; `original` reuses `photo.download`, so it respects the persisted
 * `membersCanDownload` flag (`403` when disabled). Membership failures, a
 * missing photo and a missing object all answer `404 NOT_FOUND` without
 * distinguishing the cases. Storage read failures become `500 INTERNAL_ERROR`
 * and are logged without PII or the object key.
 *
 * A matching `If-None-Match` is evaluated before touching storage and answers
 * `304` without reading the binary. This intentionally wins over «object
 * missing»: the client already holds the representation. Without a validator,
 * a missing object still answers `404`.
 */
export function registerPhotoImageRoutes(app: MemoraServer, config: AppConfig): void {
  app.get(
    '/api/photos/:photoId/image',
    {
      schema: {
        tags: [PHOTOS_TAG],
        summary: 'Imagen autenticada',
        description:
          'Entrega una variante de la foto: `thumb` (400×400 WebP), `display` (1600 px WebP) u `original`. ' +
          '`size` es obligatorio. Requiere sesión y membresía vigente en el círculo; `thumb` y `display` están ' +
          'disponibles para cualquier miembro y `original` exige `photo.download` (`403` si el círculo desactiva ' +
          '`membersCanDownload`). Foto inexistente, de otro círculo, sin membresía u objeto ausente en storage → ' +
          '`404`, sin distinguir casos. La clave del objeto se elige en servidor y nunca se devuelve. Cabeceras: ' +
          '`Content-Type` real, `Content-Length`, `Content-Disposition: inline`, `X-Content-Type-Options: nosniff`, ' +
          '`Cache-Control: private, max-age=3600`, `Vary: Cookie` y `ETag` débil; `If-None-Match` coincidente → ' +
          '`304` sin cuerpo. Sin límite de peticiones propio.',
        security: sessionSecurity,
        params: photoParamsSchema,
        querystring: photoImageQuerySchema,
        response: {
          400: errorResponseSchema,
          401: errorResponseSchema,
          403: errorResponseSchema,
          404: errorResponseSchema,
          429: errorResponseSchema,
          500: errorResponseSchema,
        },
      },
    },
    async (request, reply) => {
      const prisma = requirePrisma(app);
      const { user } = await resolveSession(prisma, config, request, reply);
      const { photoId } = request.params;
      const { size } = request.query;

      const photo = await findPhotoForMember(prisma, photoId, user.id);

      if (photo === null) {
        throw new ApiError('NOT_FOUND');
      }

      if (size === 'original') {
        assertDownloadPermission(photo, user.id);
      }

      const etag = buildImageEtag(photo.id, size, photo.updatedAt);

      // The declared response map only documents the JSON error bodies; success
      // is a raw `Buffer` that must bypass the JSON serializer. The Zod type
      // provider narrows `reply.code()` to the declared statuses, so the cast
      // restores Fastify's untyped reply for the binary path.
      const binaryReply = reply as FastifyReply;

      binaryReply
        .header('etag', etag)
        .header('cache-control', IMAGE_CACHE_CONTROL)
        .header('vary', 'Cookie');

      // Revalidation does not read storage: a matching validator wins over
      // «object missing» because the client already has the bytes.
      if (matchesIfNoneMatch(request.headers['if-none-match'], etag)) {
        return binaryReply.code(304).send();
      }

      let object: StoredObject | null;

      try {
        object = await app.services.storage.get(selectImageKey(photo, size));
      } catch {
        // The thrown error can contain the storage key or provider details:
        // neither the log nor the response may echo them.
        request.log.error({ code: 'IMAGE_STORAGE_READ_FAILED' }, 'Image storage read failed');
        throw new ApiError('INTERNAL_ERROR');
      }

      if (object === null) {
        throw new ApiError('NOT_FOUND');
      }

      binaryReply
        .header('x-content-type-options', 'nosniff')
        .header('content-disposition', 'inline')
        .header('content-type', resolveContentType(photo, size))
        .header('content-length', object.body.byteLength);

      return binaryReply.code(200).send(object.body);
    },
  );
}
